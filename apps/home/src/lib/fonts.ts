/**
 * Self-hosted fonts (nothing loads from outside the site). The woff2 subsets from `@emunas/tokens`
 * are copied to `public/fonts/` and `src/styles/fonts.css` is `@emunas/tokens/fonts.css` with its
 * URLs pointed there. Both are written by `npm run fonts:sync -w @emunas/home` and checked by
 * test/fonts.test.ts.
 */
import { preloadFonts } from "@emunas/tokens";

export const FONTS_BASE = "/fonts/";

/** Rewrites the tokens package's `url("../fonts/x.woff2")` to `url("/fonts/x.woff2")`. */
export function homeFontsCss(tokensFontsCss: string): string {
  const header = "/* Generated by apps/home/src/lib/fonts-sync.ts from @emunas/tokens/fonts.css. Do not edit. */\n";
  const body = tokensFontsCss.replace(/^\/\* Generated by [^\n]*\*\/\n/, "");
  return header + body.replaceAll('url("../fonts/', `url("${FONTS_BASE}`);
}

/** The English serif body face, preloaded on every page. */
export function fontPreloads(): string[] {
  return preloadFonts("serif", "en").map((file) => FONTS_BASE + file);
}
