/**
 * Self-hosted fonts for Quiet (concept-quiet §11: nothing loads from outside the site). The woff2
 * subsets from `@emunas/tokens` are copied to `public/fonts/` so they have stable URLs
 * (`/fonts/<file>`, cached immutable by `_headers`) and the edition's body face can be preloaded.
 * `src/styles/fonts.css` is `@emunas/tokens/fonts.css` with its relative URLs pointed there.
 * Both are written by `npm run fonts:sync -w @emunas/quiet` and checked by `test/fonts.test.ts`.
 */
import { preloadFonts } from "@emunas/tokens";
import type { Ed } from "./edition.ts";

export const FONTS_BASE = "/fonts/";

/** Rewrites the tokens package's `url("../fonts/x.woff2")` to `url("/fonts/x.woff2")`. */
export function quietFontsCss(tokensFontsCss: string): string {
  const header = "/* Generated by apps/quiet/src/lib/fonts-sync.ts from @emunas/tokens/fonts.css. Do not edit. */\n";
  const body = tokensFontsCss.replace(/^\/\* Generated by [^\n]*\*\/\n/, "");
  return header + body.replaceAll('url("../fonts/', `url("${FONTS_BASE}`);
}

/** URLs to `<link rel="preload" as="font">`: only the edition's serif body face. */
export function fontPreloads(ed: Ed): string[] {
  return preloadFonts("serif", ed).map((file) => FONTS_BASE + file);
}
