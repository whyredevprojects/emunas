import {
  FALLBACK_FACES,
  fontManifest,
  fontStacks,
  sizeAdjustOf,
  type FontFamily,
  type FontManifest,
} from "./fonts.ts";
import {
  colors,
  fontWeight,
  hebrewSizeAdjust,
  lineHeight,
  measure,
  motion,
  radius,
  rule,
  space,
  typeScale,
  type ColorRole,
} from "./tokens.ts";

const HEADER = "/* Generated by packages/tokens/scripts/build-css.ts from src/*.ts and fonts/manifest.json. Do not edit. */";

const pct = (factor: number): string => `${Math.round(factor * 100000) / 1000}%`;

function block(selector: string, declarations: readonly string[], indent = ""): string {
  return [`${indent}${selector} {`, ...declarations.map((d) => `${indent}  ${d}`), `${indent}}`].join("\n");
}

function vars(prefix: string, values: Readonly<Record<string, string>> | readonly (readonly [string, string])[]): string[] {
  const entries = Array.isArray(values) ? values : Object.entries(values);
  return entries.map(([k, v]) => `--${prefix}-${k}: ${v};`);
}

function colorVars(theme: "light" | "dark"): string[] {
  return (Object.entries(colors[theme]) as [ColorRole, string][]).map(([k, v]) => `--color-${k}: ${v};`);
}

/** css/tokens.css: every token as a custom property, colour roles for light and dark. */
export function tokensCss(): string {
  const root = [
    "color-scheme: light dark;",
    // integer-like keys ("0", "1") would otherwise come before "-2", "-1"
    ...vars("step", Object.entries(typeScale).sort(([a], [b]) => Number(a) - Number(b))),
    ...vars("leading", lineHeight),
    ...vars("weight", fontWeight),
    ...vars("measure", measure),
    ...vars("space", space),
    ...vars("radius", radius),
    ...vars("rule", rule),
    ...vars("duration", { fast: motion.fast, base: motion.base, slow: motion.slow }),
    `--ease-standard: ${motion.ease};`,
    ...vars("font", fontStacks),
    "--font-text: var(--font-serif-latin);",
    "--font-ui: var(--font-sans-latin);",
    "--leading-text: var(--leading-body);",
    ...colorVars("light"),
  ];
  const hebrew = [
    "--font-text: var(--font-serif-hebrew);",
    "--font-ui: var(--font-sans-hebrew);",
    "--leading-text: var(--leading-hebrew);",
  ];
  return [
    HEADER,
    "@layer tokens {",
    block(":root", root, "  "),
    "",
    "  /* Yiddish and Hebrew runs take the Hebrew stacks; the custom properties inherit. */",
    block(":lang(yi), :lang(he)", hebrew, "  "),
    "",
    "  @media (prefers-color-scheme: dark) {",
    block(':root:not([data-theme="light"])', colorVars("dark"), "    "),
    "  }",
    "",
    block(':root[data-theme="dark"]', ["color-scheme: dark;", ...colorVars("dark")], "  "),
    "",
    block(':root[data-theme="light"]', ["color-scheme: light;"], "  "),
    "}",
    "",
  ].join("\n");
}

const STYLE_ORDER = { normal: 0, italic: 1 } as const;

/**
 * css/fonts.css: one @font-face per subset file (unicode-range lets the browser
 * fetch only the files a page needs) plus metric-matched local fallbacks.
 * Font URLs are relative to css/, so bundlers (Vite/Astro) fingerprint and copy them.
 */
export function fontsCss(manifest: FontManifest = fontManifest): string {
  const faces = [...manifest.faces].sort(
    (a, b) => a.family.localeCompare(b.family) || STYLE_ORDER[a.style] - STYLE_ORDER[b.style] || a.id.localeCompare(b.id),
  );
  const rules = faces.map((face) => {
    const [min, max] = face.weight;
    const adjust = sizeAdjustOf(face.family, manifest);
    return block("@font-face", [
      `font-family: "${face.family}";`,
      `src: url("../fonts/${face.file}") format("woff2");`,
      `font-style: ${face.style};`,
      `font-weight: ${min === max ? String(min) : `${min} ${max}`};`,
      "font-display: swap;",
      ...(adjust === 1 ? [] : [`size-adjust: ${pct(adjust)};`]),
      `unicode-range: ${face.unicodeRange};`,
    ]);
  });

  const fallbacks = FALLBACK_FACES.map((fb) => {
    const ref = manifest.faces.find((f) => f.family === fb.of);
    if (!ref) throw new Error(`fontsCss: no face for ${fb.of}`);
    const m = ref.metrics;
    const adjust = sizeAdjustOf(fb.of as FontFamily, manifest);
    return block("@font-face", [
      `font-family: "${fb.family}";`,
      `src: ${fb.local.map((name) => `local("${name}")`).join(", ")};`,
      `ascent-override: ${pct(m.ascender / m.unitsPerEm)};`,
      `descent-override: ${pct(Math.abs(m.descender) / m.unitsPerEm)};`,
      `line-gap-override: ${pct(m.lineGap / m.unitsPerEm)};`,
      ...(adjust === 1 ? [] : [`size-adjust: ${pct(adjust)};`]),
    ]);
  });

  return [
    HEADER,
    `/* ${manifest.faces.length} subset faces, ${manifest.totalBytes} bytes of woff2 in total. Licences: fonts/licenses/ (SIL OFL 1.1). */`,
    `/* Hebrew faces are enlarged (size-adjust ${hebrewSizeAdjust.serif} serif, ${hebrewSizeAdjust.sans} sans) so Hebrew and Latin read at equal weight. */`,
    ...rules,
    "",
    "/* Local fallbacks with the web fonts' vertical metrics, to limit layout shift during swap. */",
    ...fallbacks,
    "",
  ].join("\n");
}
